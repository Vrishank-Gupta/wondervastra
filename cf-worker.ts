/**
 * Cloudflare entry point: the OpenNext-generated Next.js worker, plus a scheduled handler so
 * Cloudflare's cron trigger can run the store's housekeeping route without an outside cron service.
 *
 * Store pages for signed-out shoppers are kept in Cloudflare's edge cache and refreshed in the background
 * once a minute, so most visits don't render the page at all. Rendering costs 40-60ms of CPU, and the
 * Workers plan can cut requests off past its CPU limit; served from cache, a visit costs ~1ms.
 * Prices and stock on a cached page are at most a minute or two old; the cart and checkout always
 * re-check them fresh, so nothing can be oversold.
 */
// @ts-expect-error generated by `opennextjs-cloudflare build`
import handler from "./.open-next/worker.js";
import { htmlToMarkdown } from "./src/lib/html-md";

type Env = { CRON_SECRET?: string; NEXT_PUBLIC_SITE_URL?: string; CF_VERSION_METADATA?: { id: string } };
type Ctx = { waitUntil(p: Promise<unknown>): void };

const FRESH_MS = 60_000; // serve from cache without re-rendering
const KEEP_S = 30 * 60; // keep a stale copy this long, refreshing it in the background
const SIGNED_IN = /(?:^|;\s*)(vv_session|vv_admin)=/;
// Pages that are the same for every signed-out shopper. Everything else (cart, checkout, account, admin,
// orders, tracking, APIs) always renders fresh.
const SHARED = /^\/(?:$|c\/|p\/|shop(?:\/|$)|family-pack$|guides(?:\/|$)|brands(?:\/|$)|sale(?:\/|$)|info\/)/;
// Ad and campaign tags don't change the page; drop them so every visitor from a campaign shares one copy.
const NOISE = /^(utm_\w+|fbclid|gclid|igshid|ref|_gl)$/;

// Guides and policies as Markdown for AI assistants (/guides/<slug>.md or Accept: text/markdown), converted
// from the page's HTML. Catalogue pages have their own data-built Markdown (next.config.ts rewrites).
const MD_PAGES = /^\/(?:guides(?:\/[\w-]+)?|info\/[\w-]+|family-pack|sale)$/;
const wantsMarkdown = (req: Request) => /text\/markdown/i.test(req.headers.get("accept") ?? "");
function markdownPath(req: Request, url: URL) {
  if (req.method !== "GET") return null;
  if (url.pathname.endsWith(".md")) return MD_PAGES.test(url.pathname.slice(0, -3)) ? url.pathname.slice(0, -3) : null;
  return wantsMarkdown(req) && MD_PAGES.test(url.pathname) ? url.pathname : null;
}

async function markdown(env: Env, ctx: Ctx, url: URL, path: string) {
  const cache = (caches as unknown as { default: Cache }).default;
  const key = keyFor(new URL(`${url.origin}${path}.md`), env.CF_VERSION_METADATA?.id ?? "dev");
  const hit = await cache.match(key).catch(() => undefined);
  if (hit) return hit;
  const page: Response = await handler.fetch(new Request(`${url.origin}${path}`, { headers: { accept: "text/html" } }), env, ctx);
  if (page.status !== 200) return new Response("Not found\n", { status: 404, headers: { "content-type": "text/markdown; charset=utf-8" } });
  const out = new Response(htmlToMarkdown(await page.text(), url.origin).markdown, {
    headers: { "content-type": "text/markdown; charset=utf-8", "cache-control": "public, max-age=300", link: `<${url.origin}${path}>; rel="canonical"`, vary: "Accept" },
  });
  ctx.waitUntil(cache.put(key, out.clone()).catch(() => {}));
  return out;
}

function cacheable(req: Request, url: URL) {
  if (req.method !== "GET") return false;
  // Markdown requests are answered by a different route; never store them under the page's address.
  if (wantsMarkdown(req)) return false;
  if (!SHARED.test(url.pathname) || url.searchParams.has("_rsc")) return false;
  // Only full page loads. In-app navigations (RSC requests) vary by router state and stay uncached.
  if (req.headers.get("rsc") || req.headers.get("next-router-state-tree") || req.headers.get("next-router-prefetch")) return false;
  if (!(req.headers.get("accept") ?? "").includes("text/html")) return false;
  return !SIGNED_IN.test(req.headers.get("cookie") ?? "");
}

function keyFor(url: URL, version: string) {
  const k = new URL(url.toString());
  for (const p of [...k.searchParams.keys()]) if (NOISE.test(p)) k.searchParams.delete(p);
  k.searchParams.sort();
  // Each deploy starts a fresh cache: old pages point at the old build's script files.
  k.searchParams.set("__wv", version);
  return new Request(k.toString(), { method: "GET" });
}

async function render(req: Request, env: Env, ctx: Ctx, key: Request, cache: Cache) {
  const res: Response = await handler.fetch(req, env, ctx);
  if (res.status !== 200 || res.headers.has("set-cookie")) return res;
  const body = await res.arrayBuffer();
  const copy = new Response(body, res);
  copy.headers.set("cache-control", `public, max-age=${KEEP_S}`);
  copy.headers.set("x-wv-at", String(Date.now()));
  copy.headers.delete("vary");
  ctx.waitUntil(cache.put(key, copy.clone()).catch(() => {}));
  const out = new Response(body, res);
  out.headers.set("x-wv-cache", "miss");
  return out;
}

const refreshing = new Set<string>();
const DAILY = "30 3 * * *";

export default {
  // One secure address for the shop: http:// → https://, and www.wondervastra.in → wondervastra.in, keeping the path.
  async fetch(req: Request, env: Env, ctx: Ctx) {
    const url = new URL(req.url);
    const local = url.hostname === "localhost" || url.hostname === "127.0.0.1";
    if (!local && (url.protocol === "http:" || url.hostname.startsWith("www."))) {
      url.protocol = "https:";
      if (url.hostname.startsWith("www.")) url.hostname = url.hostname.slice(4);
      return Response.redirect(url.toString(), 301);
    }
    const md = local ? null : markdownPath(req, url);
    if (md) return markdown(env, ctx, url, md);
    if (local || !cacheable(req, url)) return handler.fetch(req, env, ctx);

    const cache = (caches as unknown as { default: Cache }).default;
    const key = keyFor(url, env.CF_VERSION_METADATA?.id ?? "dev");
    const hit = await cache.match(key).catch(() => undefined);
    if (!hit) return render(req, env, ctx, key, cache);

    const age = Date.now() - Number(hit.headers.get("x-wv-at") ?? 0);
    if (age > FRESH_MS && !refreshing.has(key.url)) {
      refreshing.add(key.url);
      ctx.waitUntil(render(new Request(req.url, { headers: req.headers }), env, ctx, key, cache).catch(() => {}).finally(() => refreshing.delete(key.url)));
    }
    const out = new Response(hit.body, hit);
    // Browsers must still ask us each time (so a refresh shows new prices); only the edge keeps a copy.
    out.headers.set("cache-control", "private, no-cache, max-age=0, must-revalidate");
    out.headers.set("x-wv-cache", age > FRESH_MS ? "stale" : "hit");
    out.headers.delete("x-wv-at");
    return out;
  },
  async scheduled(event: { cron?: string }, env: Env, ctx: Ctx) {
    if (!env.CRON_SECRET) return;
    const url = new URL("/api/cron", env.NEXT_PUBLIC_SITE_URL || "https://wondervastra.in");
    // 03:30 UTC is 9 am in India: the owner's morning summary email.
    if (event.cron === DAILY) url.searchParams.set("job", "daily");
    ctx.waitUntil(handler.fetch(new Request(url, { headers: { authorization: `Bearer ${env.CRON_SECRET}` } }), env, ctx));
  },
};
